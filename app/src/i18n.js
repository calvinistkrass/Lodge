export const LANGUAGES = { de, en };

export function systemLanguage() {
  try {
    const code = getLocales()?.[0]?.languageCode;
    return code && LANGUAGES[code] ? code : 'en';
  } catch {
    return 'en';
  }
}

export function resolveLanguage(setting) {
  return setting && setting !== 'system' && LANGUAGES[setting] ? setting : systemLanguage();
}

function lookup(dict, key) {
  return key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
}

export function translate(lang, key, vars) {
  let s = lookup(LANGUAGES[lang], key) ?? lookup(en, key) ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => resolveLanguage(s.settings.language));
  return (key, vars) => translate(lang, key, vars);
}

export function errorText(t, err) {
  const code = err?.code || 'unknown';
  const text = t(`errors.${code}`);
  return text === `errors.${code}` ? t('errors.unknown') : text;
}
